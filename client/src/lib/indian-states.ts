export const GST_STATE_CODE_BY_NAME: Record<string, string> = Object.fromEntries(
  INDIAN_STATES.map((s) => [s.name, s.code]),
);

export const GSTIN_REGEX = /^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$/;

export function isValidGstin(value: string): boolean {
  return GSTIN_REGEX.test(value.trim().toUpperCase());
}

export function stateNameForCode(code: string | null | undefined): string | undefined {
  return INDIAN_STATES.find((s) => s.code === code)?.name;
}
